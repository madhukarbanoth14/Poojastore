  final r = te
      ? localizeAlmanacTerm(rithu, te)
      : (rithu == null ? '—' : '$rithu Rithu');
  return '$a, $r';
}

String masamPakshaLine(String? masam, String? paksha, bool te) {
  final m = localizeAlmanacTerm(masam, te);
  final suffix = te ? ' మాసం' : ' Masam';
  return '$m$suffix, ${pakshaDisplay(paksha, te)}';
}

String? _clockHourMinute(String raw) {
  final m = RegExp(r'^(\d{1,2}):(\d{2})\s*(am|pm)?$', caseSensitive: false)
      .firstMatch(raw.trim());
  if (m == null) return null;
  var hour = int.parse(m.group(1)!);
  final minute = int.parse(m.group(2)!);
  final ap = m.group(3)?.toLowerCase();
  if (ap == 'pm' && hour < 12) hour += 12;
  if (ap == 'am' && hour == 12) hour = 0;
  return '$hour:$minute';
}

String formatAlmanacTime(String? value, bool te) {
  if (value == null || value.isEmpty) return '—';
  final parsed = _clockHourMinute(value);
  if (parsed == null) return value;
  final parts = parsed.split(':');
  var hour = int.parse(parts[0]);
  final minute = int.parse(parts[1]);
  final mm = minute.toString().padLeft(2, '0');
  if (!te) {
    final h12 = hour % 12 == 0 ? 12 : hour % 12;
    final ap = hour >= 12 ? 'pm' : 'am';
    return '${h12.toString().padLeft(2, '0')}:$mm $ap';
  }
  var period = 'రా';
  if (hour >= 4 && hour < 12) {
    period = 'ఉ';
  } else if (hour >= 12 && hour < 16) {
    period = 'మ';
  } else if (hour >= 16 && hour < 19) {
    period = 'సా';
  }
  final h12 = hour % 12 == 0 ? 12 : hour % 12;
  return '$period $h12.$mm';
}

String untilPhrase(String? time, bool te) {
  if (time == null || time.isEmpty) return '';
  final stamp = formatAlmanacTime(time, te);
  return te ? '$stamp వరకు' : 'until $stamp';
}

String windowPhrase(dynamic value, bool te) {
  if (value is! Map) return te ? 'లేదు' : 'None';
  final start = value['start'] as String?;
  final end = value['end'] as String?;
  if (start == null || start.isEmpty) return te ? 'లేదు' : 'None';
  return '${formatAlmanacTime(start, te)} – ${formatAlmanacTime(end, te)}';
}

String weekdayDateBanner(Map<String, dynamic> p, bool te) {
  final weekday = localizeWeekday(p['weekday'] as String?, te);
  final iso = p['date'] as String?;
  if (iso == null || iso.length < 10) return weekday;
  final y = int.parse(iso.substring(0, 4));
  final m = int.parse(iso.substring(5, 7));
  final d = int.parse(iso.substring(8, 10));
  if (!te) {
    const months = [
      'January', 'February', 'March', 'April', 'May', 'June',
      'July', 'August', 'September', 'October', 'November', 'December',
    ];
    return '$weekday, ${months[m - 1]} $d, $y';
  }
  const months = [
    'జనవరి', 'ఫిబ్రవరి', 'మార్చి', 'ఏప్రిల్', 'మే', 'జూన్',
    'జూలై', 'ఆగష్టు', 'సెప్టెంబర్', 'అక్టోబర్', 'నవంబర్', 'డిసెంబర్',
  ];
  return '$weekday, ${months[m - 1]} $d, $y';
}

String karanaValue(Map<String, dynamic> p, bool te) {
  final first = localizeAlmanacTerm(p['karana'] as String?, te);
  final until = untilPhrase(p['karanaEndsAt'] as String?, te);
  final nextName = p['karanaNext'] as String?;
  if (nextName == null || nextName.isEmpty) {
    return until.isEmpty ? first : '$first ($until)';
  }
  final second = localizeAlmanacTerm(nextName, te);
  final nextUntil = untilPhrase(p['karanaNextEndsAt'] as String?, te);
  final a = until.isEmpty ? first : '$first $until';
  final b = nextUntil.isEmpty ? second : '$second $nextUntil';
  return '$a, $b';
}

String isoDate(DateTime d) {
  final m = d.month.toString().padLeft(2, '0');
  final day = d.day.toString().padLeft(2, '0');
  return '${d.year}-$m-$day';
}

DateTime parseIsoDate(String iso) {
  final y = int.parse(iso.substring(0, 4));
  final m = int.parse(iso.substring(5, 7));
  final d = int.parse(iso.substring(8, 10));
  return DateTime(y, m, d);
}
