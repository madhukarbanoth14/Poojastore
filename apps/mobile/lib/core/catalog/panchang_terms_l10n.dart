/// Localize "15 Jan 2026" style date labels from API.
String localizeDateLabel(String? label, bool te) {
  if (label == null || label.isEmpty || !te) return label ?? '';
  final parts = label.trim().split(RegExp(r'\s+'));
  if (parts.length >= 3) {
    final day = parts[0];
    final month = localizeMonthShort(parts[1], te);
    final year = parts.sublist(2).join(' ');
    return '$day $month $year';
  }
  return label;
}

