/// Localize a panchang field value (tithi, nakshatra, yoga, karana).
String localizePanchangTerm(String? raw, bool te) {
  if (raw == null || raw.isEmpty) return '—';
  if (!te) return raw;
  var s = raw.trim();
  s = s.replaceFirst(RegExp(r'\s+Nakshatra\s*\$', caseSensitive: false), '');
  if (_termTe.containsKey(s)) return _termTe[s]!;
  final parts = s.split(RegExp(r'\s+'));
  if (parts.length >= 2) {
    final pakshaTe = _pakshaTe[parts.first];
    if (pakshaTe != null) {
      final rest = parts.sublist(1).join(' ');
      final restTe = _termTe[rest] ?? rest;
      return '$pakshaTe $restTe';
    }
  }
  return s;
}

/// Tithi and nakshatra on one line.
String localizeTithiNakshatraLine(String? tithi, String? nakshatra, bool te) {
  final t = localizePanchangTerm(tithi, te);
  final n = localizePanchangTerm(nakshatra, te);
  return '$t · $n';
}

